-- =====================================================================
-- CityRoute — Support Chat: schema, RLS, RPC functions
-- =====================================================================
-- Run in Supabase SQL Editor AFTER 001_initial.sql (needs public.profiles).
-- Then run 010_support_chat_storage.sql.
--
-- This migration is additive. It does NOT touch GPS / routes / pins /
-- payments / profiles tables or any payment function.
--
-- SECURITY MODEL (read this before changing anything)
--   * Clients (anon / authenticated) can only SELECT support data, and only
--     through RLS (own conversations, or everything for support admins).
--   * Clients have NO INSERT / UPDATE / DELETE privilege on any support
--     table. All writes go through SECURITY DEFINER functions below, which
--     derive the author (user vs admin) from auth.uid() on the server.
--     A client can therefore never post "as admin" or into someone else's
--     conversation, whatever it sends.
--   * "Who is an admin" lives in public.support_admins. Authenticated users
--     may only read their OWN row there; nobody but the database owner /
--     service_role can write it. It is deliberately NOT a column on
--     public.profiles, because profiles has an "update own row" policy and
--     a column there could be self-granted.
--   * service_role key is never used from the browser.
-- =====================================================================

create extension if not exists "pgcrypto";

-- ---------------------------------------------------------------------
-- 1. Trusted support-admin list
-- ---------------------------------------------------------------------
create table if not exists public.support_admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  note text,
  created_at timestamptz not null default now()
);

alter table public.support_admins enable row level security;

drop policy if exists support_admins_select_own on public.support_admins;
create policy support_admins_select_own
  on public.support_admins for select to authenticated
  using (user_id = (select auth.uid()));

revoke all on public.support_admins from anon, authenticated;
grant select on public.support_admins to authenticated;

create or replace function public.is_support_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.support_admins a where a.user_id = auth.uid()
  );
$$;

revoke all on function public.is_support_admin() from public, anon;
grant execute on function public.is_support_admin() to authenticated, service_role;

-- ---------------------------------------------------------------------
-- 2. Conversations
-- ---------------------------------------------------------------------
-- One user may have several conversations (model allows it); the app v1
-- uses the most recent one via get_or_create_support_conversation().
create table if not exists public.support_conversations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  status text not null default 'open'
    check (status in ('open', 'waiting', 'resolved')),
  last_message_at timestamptz not null default now(),
  last_message_preview text not null default '',
  last_sender_type text check (last_sender_type in ('user', 'admin')),
  user_unread_count integer not null default 0 check (user_unread_count >= 0),
  admin_unread_count integer not null default 0 check (admin_unread_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists support_conversations_user_idx
  on public.support_conversations (user_id, last_message_at desc);
create index if not exists support_conversations_status_idx
  on public.support_conversations (status, last_message_at desc);

-- ---------------------------------------------------------------------
-- 3. Messages
-- ---------------------------------------------------------------------
create table if not exists public.support_messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null
    references public.support_conversations (id) on delete cascade,
  sender_id uuid references auth.users (id) on delete set null,
  sender_type text not null check (sender_type in ('user', 'admin')),
  body text not null default '' check (char_length(body) <= 4000),
  -- Idempotency key generated by the sending client: a retry of the same
  -- message never creates a duplicate row.
  client_id uuid,
  read_at timestamptz,
  created_at timestamptz not null default now(),
  unique (sender_id, client_id)
);

create index if not exists support_messages_conversation_idx
  on public.support_messages (conversation_id, created_at, id);

-- ---------------------------------------------------------------------
-- 4. Attachment metadata (files live in the PRIVATE storage bucket
--    "support-attachments"; see 010_support_chat_storage.sql)
-- ---------------------------------------------------------------------
create table if not exists public.support_message_attachments (
  id uuid primary key default gen_random_uuid(),
  message_id uuid not null
    references public.support_messages (id) on delete cascade,
  conversation_id uuid not null
    references public.support_conversations (id) on delete cascade,
  storage_path text not null unique,
  mime_type text not null
    check (mime_type in ('image/jpeg', 'image/png', 'image/webp')),
  size_bytes integer not null check (size_bytes > 0 and size_bytes <= 5242880),
  created_at timestamptz not null default now()
);

create index if not exists support_message_attachments_message_idx
  on public.support_message_attachments (message_id);
create index if not exists support_message_attachments_conversation_idx
  on public.support_message_attachments (conversation_id);

-- ---------------------------------------------------------------------
-- 5. E-mail outbox (processed by the support-notify Edge Function).
--    A failed e-mail never affects the saved chat message.
-- ---------------------------------------------------------------------
create table if not exists public.support_email_outbox (
  id uuid primary key default gen_random_uuid(),
  message_id uuid not null
    references public.support_messages (id) on delete cascade,
  conversation_id uuid not null
    references public.support_conversations (id) on delete cascade,
  kind text not null check (kind in ('admin_new_message', 'user_reply')),
  status text not null default 'pending'
    check (status in ('pending', 'sending', 'sent', 'failed', 'skipped')),
  attempts integer not null default 0,
  next_attempt_at timestamptz not null default now(),
  claimed_at timestamptz,
  last_error text,
  created_at timestamptz not null default now(),
  sent_at timestamptz,
  unique (message_id, kind)
);

create index if not exists support_email_outbox_due_idx
  on public.support_email_outbox (status, next_attempt_at);
create index if not exists support_email_outbox_conv_idx
  on public.support_email_outbox (conversation_id, kind, created_at desc);

