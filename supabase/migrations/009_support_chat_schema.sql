create or replace function public.support_admin_list_conversations(
  p_status text default null,
  p_limit integer default 100
)
returns table (
  id uuid,
  user_id uuid,
  status text,
  last_message_at timestamptz,
  last_message_preview text,
  last_sender_type text,
  admin_unread_count integer,
  created_at timestamptz,
  full_name text,
  email text
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_support_admin() then
    raise exception 'forbidden';
  end if;
  if p_status is not null and p_status not in ('open', 'waiting', 'resolved') then
    raise exception 'invalid_status';
  end if;

  return query
  select c.id, c.user_id, c.status, c.last_message_at, c.last_message_preview,
         c.last_sender_type, c.admin_unread_count, c.created_at,
         p.full_name, u.email::text
  from public.support_conversations c
  left join public.profiles p on p.id = c.user_id
  left join auth.users u on u.id = c.user_id
  where p_status is null or c.status = p_status
  order by c.last_message_at desc
  limit greatest(1, least(coalesce(p_limit, 100), 500));
end;
$$;

revoke all on function public.support_admin_list_conversations(text, integer) from public, anon;
grant execute on function public.support_admin_list_conversations(text, integer) to authenticated;

create or replace function public.support_admin_set_status(
  p_conversation_id uuid,
  p_status text
)
returns public.support_conversations
language plpgsql
security definer
set search_path = public
as $$
declare
  conv public.support_conversations;
begin
  if not public.is_support_admin() then
    raise exception 'forbidden';
  end if;
  if p_status is null or p_status not in ('open', 'waiting', 'resolved') then
    raise exception 'invalid_status';
  end if;

  update public.support_conversations
  set status = p_status, updated_at = now()
