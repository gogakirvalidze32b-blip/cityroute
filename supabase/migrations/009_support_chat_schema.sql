-- ---------------------------------------------------------------------
-- 11. Server-only functions used by the support-notify Edge Function
--     (service_role only — never callable from the browser)
-- ---------------------------------------------------------------------
create or replace function public.support_claim_email_outbox(p_limit integer default 10)
returns table (
  outbox_id uuid,
  kind text,
  attempts integer,
  message_id uuid,
  conversation_id uuid,
  body text,
  attachment_count integer,
  user_id uuid,
  full_name text,
  user_email text
)
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  with due as (
    select o.id
    from public.support_email_outbox o
    where o.attempts < 5
      and (
        (o.status in ('pending', 'failed') and o.next_attempt_at <= now())
        or (o.status = 'sending' and o.claimed_at < now() - interval '5 minutes')
      )
    order by o.created_at
    limit greatest(1, least(coalesce(p_limit, 10), 50))
    for update skip locked
  ),
  claimed as (
    update public.support_email_outbox o
    set status = 'sending',
        attempts = o.attempts + 1,
        claimed_at = now()
    from due
    where o.id = due.id
    returning o.id, o.kind, o.attempts, o.message_id, o.conversation_id
  )
  select cl.id, cl.kind, cl.attempts, cl.message_id, cl.conversation_id,
         m.body,
         (select count(*)::integer from public.support_message_attachments a
           where a.message_id = m.id),
         c.user_id, p.full_name, u.email::text
  from claimed cl
  join public.support_messages m on m.id = cl.message_id
  join public.support_conversations c on c.id = cl.conversation_id
  left join public.profiles p on p.id = c.user_id
  left join auth.users u on u.id = c.user_id;
end;
$$;

revoke all on function public.support_claim_email_outbox(integer) from public, anon, authenticated;
grant execute on function public.support_claim_email_outbox(integer) to service_role;

create or replace function public.support_complete_email_outbox(
  p_outbox_id uuid,
  p_ok boolean,
  p_error text default null,
  p_skipped boolean default false
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_ok then
    update public.support_email_outbox
    set status = case when p_skipped then 'skipped' else 'sent' end,
        sent_at = case when p_skipped then null else now() end,
        last_error = left(p_error, 500)
    where id = p_outbox_id;
  else
    -- Back-off: 1, 4, 9, 16 minutes. After 5 attempts the row stays 'failed'.
    update public.support_email_outbox
    set status = 'failed',
        last_error = left(coalesce(p_error, 'unknown error'), 500),
        next_attempt_at = now() + (attempts * attempts) * interval '1 minute'
    where id = p_outbox_id;
  end if;
end;
$$;

revoke all on function public.support_complete_email_outbox(uuid, boolean, text, boolean) from public, anon, authenticated;
grant execute on function public.support_complete_email_outbox(uuid, boolean, text, boolean) to service_role;

