  using (
    exists (
      select 1 from public.support_conversations c
      where c.id = support_messages.conversation_id
        and c.user_id = (select auth.uid())
    )
    or (select public.is_support_admin())
  );

drop policy if exists support_attachments_select on public.support_message_attachments;
create policy support_attachments_select
  on public.support_message_attachments for select to authenticated
  using (
    exists (
      select 1 from public.support_conversations c
      where c.id = support_message_attachments.conversation_id
        and c.user_id = (select auth.uid())
    )
    or (select public.is_support_admin())
  );

-- ---------------------------------------------------------------------
-- 7. RPC: get (or create) the caller's conversation
-- ---------------------------------------------------------------------
-- Deliberately does NOT require an active subscription: an expired user
-- with a payment problem must still be able to reach support.
create or replace function public.get_or_create_support_conversation()
returns public.support_conversations
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  conv public.support_conversations;
begin
  if uid is null then
    raise exception 'not_authenticated' using errcode = '28000';
  end if;

  -- Serialise concurrent first-time calls (two tabs) so only one row is made.
  perform pg_advisory_xact_lock(hashtextextended('support_conv:' || uid::text, 0));

  select * into conv
  from public.support_conversations
  where user_id = uid
  order by last_message_at desc
  limit 1;

  if not found then
    insert into public.support_conversations (user_id)
    values (uid)
    returning * into conv;
  end if;

  return conv;
end;
$$;

revoke all on function public.get_or_create_support_conversation() from public, anon;
grant execute on function public.get_or_create_support_conversation() to authenticated;

-- ---------------------------------------------------------------------
-- 8. RPC: send a message (the ONLY write path for messages)
-- ---------------------------------------------------------------------
-- p_attachments: jsonb array of {"path","mime","size"}; files must already
-- be uploaded to the private bucket by the SAME user, inside the folder
-- <conversation_id>/ . Everything is verified against storage.objects.
-- p_as_admin: honoured ONLY if the caller is in support_admins; otherwise
-- the call fails with 'forbidden'.
create or replace function public.send_support_message(
  p_conversation_id uuid,
  p_body text,
  p_client_id uuid,
  p_attachments jsonb default '[]'::jsonb,
  p_as_admin boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  v_is_admin boolean;
  conv public.support_conversations;
  msg public.support_messages;
  v_type text;
  v_body text;
  v_att jsonb;
  v_path text;
  v_mime text;
  v_size bigint;
  v_obj record;
  v_ext text;
  v_kind text;
  v_recent boolean;
  v_att_count integer;
  v_result jsonb;
  v_existing boolean := false;
begin
  if uid is null then
    raise exception 'not_authenticated' using errcode = '28000';
  end if;
  if p_client_id is null then
    raise exception 'client_id_required';
  end if;

  v_is_admin := public.is_support_admin();

  if p_as_admin and not v_is_admin then
    raise exception 'forbidden';
  end if;

  -- Lock the conversation row: serialises counters and status changes.
  select * into conv
  from public.support_conversations
  where id = p_conversation_id
  for update;

  -- Same error for "does not exist" and "not yours": no enumeration.
  if not found or (conv.user_id <> uid and not (v_is_admin and p_as_admin)) then
    raise exception 'conversation_not_found';
  end if;

  v_type := case when p_as_admin then 'admin' else 'user' end;

  -- Idempotent retry: same (sender, client_id) returns the stored message.
  select * into msg
  from public.support_messages
  where sender_id = uid and client_id = p_client_id;

  if found then
    if msg.conversation_id <> conv.id then
      raise exception 'client_id_conflict';
    end if;
    v_existing := true;
  else
    v_body := btrim(coalesce(p_body, ''));
    if char_length(v_body) > 4000 then
      raise exception 'body_too_long';
    end if;

    if p_attachments is null or jsonb_typeof(p_attachments) <> 'array' then
      raise exception 'invalid_attachments';
    end if;
    v_att_count := jsonb_array_length(p_attachments);
    if v_att_count > 5 then
      raise exception 'too_many_attachments';
    end if;
    if v_type = 'admin' and v_att_count > 0 then
      raise exception 'admin_attachments_unsupported';
    end if;
    if v_body = '' and v_att_count = 0 then
      raise exception 'empty_message';
    end if;

    -- Abuse limit for end users: 20 messages / 60 s.
    if v_type = 'user' and (
      select count(*) from public.support_messages m
      where m.sender_id = uid and m.created_at > now() - interval '60 seconds'
    ) >= 20 then
      raise exception 'rate_limited';
    end if;

    -- Validate every attachment against what is REALLY in storage.
    for v_att in select * from jsonb_array_elements(p_attachments) loop
      v_path := v_att ->> 'path';
      v_mime := v_att ->> 'mime';

      if v_mime not in ('image/jpeg', 'image/png', 'image/webp') then
        raise exception 'attachment_type_not_allowed';
      end if;
      v_ext := case v_mime
        when 'image/jpeg' then 'jpg'
        when 'image/png' then 'png'
        else 'webp'
      end;

      if v_path is null
         or v_path !~ ('^' || conv.id::text || '/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.' || v_ext || '$') then
        raise exception 'attachment_path_invalid';
      end if;

      select o.metadata, o.owner_id, o.owner into v_obj
      from storage.objects o
      where o.bucket_id = 'support-attachments' and o.name = v_path;

      if not found then
        raise exception 'attachment_missing';
      end if;
      if coalesce(v_obj.owner_id, v_obj.owner::text) is distinct from uid::text then
        raise exception 'attachment_not_owned';
      end if;
      if (v_obj.metadata ->> 'mimetype') is distinct from v_mime then
        raise exception 'attachment_type_mismatch';
      end if;
      v_size := (v_obj.metadata ->> 'size')::bigint;
      if v_size is null or v_size < 1 or v_size > 5242880 then
        raise exception 'attachment_too_large';
      end if;
    end loop;

    insert into public.support_messages
      (conversation_id, sender_id, sender_type, body, client_id)
    values
      (conv.id, uid, v_type, v_body, p_client_id)
    returning * into msg;

    for v_att in select * from jsonb_array_elements(p_attachments) loop
      select (o.metadata ->> 'size')::integer into v_size
      from storage.objects o
      where o.bucket_id = 'support-attachments' and o.name = v_att ->> 'path';

      insert into public.support_message_attachments
        (message_id, conversation_id, storage_path, mime_type, size_bytes)
      values
        (msg.id, conv.id, v_att ->> 'path', v_att ->> 'mime', v_size);
    end loop;

    update public.support_conversations c
    set last_message_at = msg.created_at,
        last_message_preview = left(
          regexp_replace(
            case when v_body <> '' then v_body else '📎 სურათი' end,
            '\s+', ' ', 'g'),
          140),
        last_sender_type = v_type,
        admin_unread_count = c.admin_unread_count + case when v_type = 'user' then 1 else 0 end,
        user_unread_count = c.user_unread_count + case when v_type = 'admin' then 1 else 0 end,
        status = case
          when v_type = 'user' then 'open'
          when c.status = 'open' then 'waiting'
          else c.status
        end,
        updated_at = now()
    where c.id = conv.id;

    -- E-mail notification job. Several messages within 2 minutes in the
    -- same direction are coalesced into one e-mail.
    v_kind := case when v_type = 'user' then 'admin_new_message' else 'user_reply' end;
    v_recent := exists (
      select 1 from public.support_email_outbox o
      where o.conversation_id = conv.id
        and o.kind = v_kind
        and o.status in ('pending', 'sending', 'sent')
        and o.created_at > now() - interval '2 minutes'
    );
    insert into public.support_email_outbox
      (message_id, conversation_id, kind, status, last_error)
    values
      (msg.id, conv.id, v_kind,
       case when v_recent then 'skipped' else 'pending' end,
       case when v_recent then 'coalesced' else null end);
  end if;

  select jsonb_build_object(
    'message', to_jsonb(msg),
    'attachments', coalesce((
      select jsonb_agg(to_jsonb(a) order by a.created_at, a.id)
      from public.support_message_attachments a
      where a.message_id = msg.id
    ), '[]'::jsonb),
    'deduplicated', v_existing
  ) into v_result;

  return v_result;
end;
$$;

revoke all on function public.send_support_message(uuid, text, uuid, jsonb, boolean) from public, anon;
grant execute on function public.send_support_message(uuid, text, uuid, jsonb, boolean) to authenticated;

-- ---------------------------------------------------------------------
-- 9. RPC: mark the other party's messages as read
-- ---------------------------------------------------------------------
create or replace function public.mark_support_read(
  p_conversation_id uuid,
  p_as_admin boolean default false
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  conv public.support_conversations;
  v_is_admin boolean;
begin
  if uid is null then
    raise exception 'not_authenticated' using errcode = '28000';
  end if;

  v_is_admin := public.is_support_admin();
  if p_as_admin and not v_is_admin then
    raise exception 'forbidden';
  end if;

  select * into conv
  from public.support_conversations
  where id = p_conversation_id
  for update;

  if not found or (conv.user_id <> uid and not (v_is_admin and p_as_admin)) then
    raise exception 'conversation_not_found';
  end if;

  if p_as_admin then
    update public.support_messages
    set read_at = now()
    where conversation_id = conv.id and sender_type = 'user' and read_at is null;
    update public.support_conversations
    set admin_unread_count = 0
    where id = conv.id and admin_unread_count <> 0;
  else
    update public.support_messages
    set read_at = now()
    where conversation_id = conv.id and sender_type = 'admin' and read_at is null;
    update public.support_conversations
    set user_unread_count = 0
    where id = conv.id and user_unread_count <> 0;
  end if;
end;
$$;

revoke all on function public.mark_support_read(uuid, boolean) from public, anon;
grant execute on function public.mark_support_read(uuid, boolean) to authenticated;

