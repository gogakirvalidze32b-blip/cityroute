/**
 * Old-vs-new comparison report for the chainage migration.
 * Always asserts; writes docs/chainage-migration/PIN_COMPARISON_REPORT.md with
 *   $env:WRITE_MIGRATION_REPORT='1'; npx vitest run src/test/migration-baseline/comparison-report.test.ts
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'
import { captureBaseline, type MigrationBaseline } from './capture-baseline'
import { pinChainageTable } from '@/data/pin-chainage'
import { routeGeometryVersion } from '@/data/route-geometry'
import { offsetMeters } from '@/lib/pin-chainage-geometry'

const BASELINE = JSON.parse(
  readFileSync(resolve(__dirname, 'pin-route-baseline.json'), 'utf8'),
) as MigrationBaseline
const REPORT = resolve(__dirname, '../../../docs/chainage-migration/PIN_COMPARISON_REPORT.md')

describe('old vs new comparison report', () => {
  it('every PIN, instruction, audio file, route geometry and speed band is unchanged', () => {
    const current = captureBaseline()
    const lines: string[] = [
      '# CityRoute chainage migration — old vs new comparison',
      '',
      '_Generated by `src/test/migration-baseline/comparison-report.test.ts`. "Old" = pre-migration snapshot (pin-route-baseline.json); "New" = current code (PIN positions derived from route kilometre + exact offset on the frozen geometry)._',
      '',
      `Session audio: start \`${decodeURIComponent(current.sessionAudio.start)}\`, finish \`${decodeURIComponent(current.sessionAudio.finish)}\`, success \`${decodeURIComponent(current.sessionAudio.success)}\` — ${JSON.stringify(current.sessionAudio) === JSON.stringify(BASELINE.sessionAudio) ? 'UNCHANGED' : 'CHANGED'}`,
      '',
    ]
    let differences = 0
    for (const old of BASELINE.routes) {
      const now = current.routes.find((route) => route.slug === old.slug)!
      const table = pinChainageTable(old.slug)!
      const geometrySame = now.examRouteLine.hash === old.examRouteLine.hash && now.examMapRouteLines.hash === old.examMapRouteLines.hash
      const bandsSame = JSON.stringify(now.speedKmBands) === JSON.stringify(old.speedKmBands)
      lines.push(`## ${old.slug}`, '')
      lines.push(`- PINs: old ${old.pinCount}, new ${now.pinCount} — ${old.pinCount === now.pinCount ? 'same' : 'DIFFERENT'}`)
      lines.push(`- Route geometry: old \`${old.examRouteLine.hash}\` (${old.examRouteLine.points} pts, ${old.examRouteLine.lengthMeters.toFixed(1)} m) → new \`${now.examRouteLine.hash}\` (${now.examRouteLine.points} pts, ${now.examRouteLine.lengthMeters.toFixed(1)} m), map lines ${geometrySame ? 'identical' : 'DIFFERENT'}; frozen version \`${routeGeometryVersion(old.slug)}\``)
      lines.push(`- Speed-limit km bands: ${bandsSame ? 'identical' : 'DIFFERENT'} (${(old.speedKmBands as unknown[]).length} bands)`)
      lines.push('')
      lines.push('| # | km | lead m | offset m | old lat, lng | new lat, lng | position | instruction | audio | radius |')
      lines.push('|---|---:|---:|---:|---|---|---|---|---|---|')
      for (const pin of old.pins) {
        const next = now.pins.find((item) => item.sort_order === pin.sort_order)
        const entry = table.pins.find((item) => item.sort_order === pin.sort_order)!
        const samePosition = next?.lat === pin.lat && next?.lng === pin.lng
        const sameText = next?.instruction_ka === pin.instruction_ka
        const sameAudio = next?.audio_url === pin.audio_url
        const sameRadius = next?.audio_trigger_distance_m === pin.audio_trigger_distance_m
        if (!samePosition || !sameText || !sameAudio || !sameRadius) differences += 1
        const audioFile = pin.audio_url ? decodeURIComponent(pin.audio_url).split('/').pop() : '—'
        lines.push(
          `| ${pin.sort_order} | ${(entry.chainage_m / 1000).toFixed(3)} | ${entry.lead_m} | ${offsetMeters(entry, pin.lat).toFixed(1)} | ${pin.lat}, ${pin.lng} | ${next?.lat}, ${next?.lng} | ${samePosition ? 'identical' : '**CHANGED**'} | ${sameText ? 'same' : '**CHANGED**'}: ${pin.instruction_ka} | ${sameAudio ? 'same' : '**CHANGED**'}: ${audioFile} | ${sameRadius ? 'same' : '**CHANGED**'} |`,
        )
      }
      lines.push('')
      expect(geometrySame, old.slug).toBe(true)
      expect(bandsSame, old.slug).toBe(true)
      expect(now.pinCount).toBe(old.pinCount)
    }
    lines.push(`**Result: ${differences === 0 ? 'NO differences — every PIN position, order, instruction, audio file and trigger radius is identical.' : `${differences} PIN(s) differ.`}**`, '')
    expect(differences).toBe(0)
    if (process.env.WRITE_MIGRATION_REPORT === '1') {
      mkdirSync(resolve(REPORT, '..'), { recursive: true })
      writeFileSync(REPORT, lines.join('\n'), 'utf8')
    }
  })
})
